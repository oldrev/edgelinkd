// Regenerate with: node scripts/generate_file_encodings.cjs
// Source: the pinned Node-RED checkout's MIT-licensed iconv-lite SBCS tables.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const base = path.join(root, '3rd-party/node-red/node_modules/iconv-lite');
const iconv = require(base);
const version = require(path.join(base, 'package.json')).version;
const spec = fs.readFileSync(path.join(root, '3rd-party/node-red/test/nodes/core/storage/10-file_spec.js'), 'utf8');
const labels = [...new Set([...spec.matchAll(/should read in a file with "([^"]+)" encoding/g)].map(m => m[1]))].sort();
const tables = [], aliases = [], fixtures = [];
for (const label of labels) {
    if (label === 'none') continue;
    const codec = iconv.getCodec(label);
    if (!codec.decodeBuf || !codec.encodeBuf) continue; // multi-byte codecs remain separate
    const decode = Array.from({length:256}, (_, i) => codec.decodeBuf.readUInt16LE(i*2));
    const key = JSON.stringify(decode);
    let index = tables.findIndex(t => t.key === key);
    if (index < 0) {
        index = tables.length;
        // Use iconv's actual encode table to preserve duplicate mappings and replacement bytes.
        const encode = [];
        for (let code = 0; code < 65536; code++) {
            if (codec.encodeBuf[code] !== 63) encode.push([code, codec.encodeBuf[code]]);
        }
        tables.push({key, decode, encode});
    }
    aliases.push([label.toLowerCase().replace(/[^a-z0-9]/g, ''), index]);
    const bytes = Buffer.from(Array.from({length:256}, (_, i) => i));
    const text = iconv.decode(bytes, label, {stripBOM:false});
    const input = text + '漢字😀';
    fixtures.push({label, bytes:[...bytes], text, input, encoded:[...iconv.encode(input, label)]});
}
let source = `// Generated by scripts/generate_file_encodings.cjs; DO NOT EDIT.\n// iconv-lite ${version}; MIT, copyright (c) 2011 Alexander Shtuchkin.\n// License: file_encodings.LICENSE\n`;
source += `pub(super) const TABLES: &[super::Table] = &[\n`;
for (const table of tables) {
    source += '    (&[' + table.decode.join(',') + '], &[' + table.encode.map(([c,b]) => `(${c},${b})`).join(',') + ']),\n';
}
source += '];\npub(super) const LABELS: &[(&str, usize)] = &[\n';
for (const [label,index] of aliases) source += `    ("${label}", ${index}),\n`;
source += '];\n';
const dest = path.join(root, 'crates/core/src/runtime/nodes/storage_nodes');
fs.writeFileSync(path.join(dest, 'file_encodings_data.rs'), source);
fs.copyFileSync(path.join(base, 'LICENSE'), path.join(dest, 'file_encodings.LICENSE'));
fs.writeFileSync(path.join(root, 'tests/resources/file_encodings.json'), JSON.stringify({version, fixtures}, null, 2)+'\n');
console.log(`${aliases.length} labels, ${tables.length} distinct SBCS tables`);
